import { useMemo } from 'react';
import { formatDayTime, formatDuration, formatMiles, routeLetter } from '../../lib/format';
import { RISK_KEY, RISK_LEVELS } from '../../lib/risk';
import { useAppStore } from '../../store/useAppStore';
import type { RouteResult } from '../../types';
import { CheckpointTable } from './CheckpointTable';

/** The three route cards, best-ranked first. The selected card expands to its checkpoints. */
export function RouteList() {
  const analysis = useAppStore((s) => s.analysis);
  const selectedId = useAppStore((s) => s.selectedRouteId);
  const selectRoute = useAppStore((s) => s.selectRoute);

  const ordered = useMemo(
    () => (analysis ? [...analysis.routes].sort((a, b) => a.rank - b.rank) : []),
    [analysis],
  );
  if (!analysis) return null;
  const letterOf = (id: string) => routeLetter(analysis.routes.findIndex((r) => r.id === id));

  return (
    <section className="routes" aria-label="Route options">
      <h2 className="section-title">
        {ordered.length} route option{ordered.length === 1 ? '' : 's'}
        <span className="section-title__meta">ranked by weather risk, then time</span>
      </h2>
      {analysis.recommendation_reason && (
        <p className="recommendation">
          <svg viewBox="0 0 16 16" width="14" height="14" aria-hidden="true">
            <path d="M8 1.5l1.9 4 4.4.5-3.3 3 .9 4.4L8 11.2 4.1 13.4 5 9 1.7 6l4.4-.5z" fill="currentColor" />
          </svg>
          <span>
            <strong>Route {letterOf(analysis.recommended_route_id)} recommended.</strong>{' '}
            {analysis.recommendation_reason}
          </span>
        </p>
      )}
      <ol className="route-list">
        {ordered.map((route) => (
          <li key={route.id}>
            <RouteCard
              route={route}
              letter={letterOf(route.id)}
              selected={route.id === selectedId}
              onSelect={() => selectRoute(route.id)}
            />
          </li>
        ))}
      </ol>
    </section>
  );
}

function RouteCard({
  route,
  letter,
  selected,
  onSelect,
}: {
  route: RouteResult;
  letter: string;
  selected: boolean;
  onSelect: () => void;
}) {
  const totalMiles = RISK_LEVELS.reduce((sum, l) => sum + route.risk_miles[RISK_KEY[l]], 0) || 1;

  return (
    <article className={`route-card${selected ? ' is-selected' : ''}${route.is_viable ? '' : ' is-blocked'}`}>
      <button type="button" className="route-card__head" onClick={onSelect} aria-expanded={selected}>
        <span className="route-card__letter">{letter}</span>
        <span className="route-card__title">
          <span className="route-card__name">{route.summary || `Route ${letter}`}</span>
          <span className="route-card__stats">
            {formatMiles(route.total_distance_miles)} · {formatDuration(route.total_duration_mins)} · arrives{' '}
            {formatDayTime(route.arrival_time)}
          </span>
        </span>
        <span className="route-card__badges">
          {route.is_recommended && <span className="badge badge--good">Recommended</span>}
          {!route.is_viable && <span className="badge badge--blocked">No Travel</span>}
          {route.is_generated_detour && (
            <span className="badge badge--muted" title="Generated by routing through a detour waypoint">
              Alt
            </span>
          )}
        </span>
      </button>

      <div className="risk-bar" role="img" aria-label={riskBarLabel(route)}>
        {RISK_LEVELS.map((l) => {
          const miles = route.risk_miles[RISK_KEY[l]];
          return miles > 0 ? (
            <span
              key={l}
              className={`risk-bar__seg risk-${RISK_KEY[l]}`}
              style={{ width: `${(miles / totalMiles) * 100}%` }}
              title={`${l}: ${formatMiles(miles)}`}
            />
          ) : null;
        })}
      </div>

      <dl className="route-card__metrics">
        <Metric label="No Travel" value={route.risk_miles.no_travel} riskKey="no_travel" />
        <Metric label="Severe" value={route.risk_miles.severe} riskKey="severe" />
        <Metric label="High" value={route.risk_miles.high} riskKey="high" />
        <div className="metric">
          <dt>Avg risk</dt>
          <dd>{route.avg_risk_score.toFixed(2)}<span className="metric__unit">/4</span></dd>
        </div>
      </dl>

      {selected && <CheckpointTable route={route} />}
    </article>
  );
}

function Metric({ label, value, riskKey }: { label: string; value: number; riskKey: string }) {
  return (
    <div className={`metric${value > 0 ? ` metric--hot risk-${riskKey}` : ''}`}>
      <dt>{label}</dt>
      <dd>
        {Math.round(value)}
        <span className="metric__unit"> mi</span>
      </dd>
    </div>
  );
}

function riskBarLabel(route: RouteResult): string {
  return RISK_LEVELS.map((l) => `${l} ${Math.round(route.risk_miles[RISK_KEY[l]])} miles`).join(', ');
}
